"""WAF fingerprinting from a normal and an attack-looking request (TRD 7, PRD F-47).

TRD 7 planned nuclei WAF templates; the official template set is not pinned yet (F6), so the
same signatures run here as a custom check: response headers, cookies, and block-page text,
plus whether an obviously malicious query is refused while the normal request is not.
"""

from __future__ import annotations

from dataclasses import dataclass

# (name, header names, header value fragments, cookie prefixes, body fragments)
SIGNATURES: list[tuple[str, tuple[str, ...], tuple[str, ...], tuple[str, ...], tuple[str, ...]]] = [
    ("Cloudflare", ("cf-ray", "cf-cache-status"), ("cloudflare",), ("__cf_bm", "cf_clearance"),
     ("attention required! | cloudflare", "cloudflare ray id")),
    ("Akamai", ("akamai-grn", "x-akamai-transformed"), ("akamaighost",), ("ak_bmsc", "bm_sz"),
     ("reference&#32;&#35;", "access denied</h1>")),
    ("Imperva Incapsula", ("x-iinfo", "x-cdn"), ("incapsula",), ("incap_ses_", "visid_incap_"),
     ("incapsula incident id", "_incapsula_resource")),
    ("F5 BIG-IP ASM", (), ("bigip", "big-ip"), ("bigipserver", "ts01", "f5_cspm"),
     ("the requested url was rejected", "support id is")),
    ("AWS WAF", ("x-amzn-waf-action",), ("awselb",), ("awsalb", "aws-waf-token"),
     ("request blocked", "generated by cloudfront")),
    ("ModSecurity", (), ("mod_security", "modsecurity", "nyob"), (),
     ("mod_security", "modsecurity", "this error was generated by mod_security")),
    ("FortiWeb", (), ("fortiweb",), ("fortiwafsid", "cookiesession1"),
     (".fgd_icon", "fortigate application control", "web page blocked")),
    ("Barracuda", (), ("barracuda",), ("barra_counter_session", "bni__barracuda"),
     ("barracuda networks",)),
    ("Sucuri", ("x-sucuri-id", "x-sucuri-cache"), ("sucuri",), (), ("sucuri website firewall",)),
    ("Wallarm", (), ("nginx-wallarm",), (), ("wallarm",)),
]  # fmt: skip
BLOCK_STATUSES = {403, 406, 429, 501, 503, 999}
ATTACK_QUERY = {"q": "<script>alert(1)</script>", "id": "1' OR '1'='1", "file": "../../etc/passwd"}


@dataclass(frozen=True)
class Sample:
    status: int | None
    headers: dict[str, str]  # lower-case names
    cookies: list[str]  # cookie names
    body: str


def _match(sample: Sample) -> tuple[str, str] | None:
    body = sample.body[:200_000].lower()
    cookies = [c.lower() for c in sample.cookies]
    for name, header_names, values, cookie_prefixes, body_texts in SIGNATURES:
        for header in header_names:
            if header in sample.headers:
                return name, f"header {header}"
        for header in ("server", "x-powered-by", "via"):
            value = sample.headers.get(header, "").lower()
            if any(v in value for v in values):
                return name, f"header {header}: {sample.headers[header]}"
        for prefix in cookie_prefixes:
            if any(c.startswith(prefix) for c in cookies):
                return name, f"cookie {prefix}"
        for text in body_texts:
            if text in body:
                return name, f"halaman blokir berisi '{text}'"
    return None


def detect(baseline: Sample, attack: Sample) -> dict[str, object]:
    """{detected, name, evidence, blocks_attacks}; name is None for an unknown blocker."""
    blocks = (
        attack.status in BLOCK_STATUSES
        and baseline.status is not None
        and baseline.status not in BLOCK_STATUSES
    )
    found = _match(attack) or _match(baseline)
    if found:
        name, evidence = found
        return {"detected": True, "name": name, "evidence": evidence, "blocks_attacks": blocks}
    if blocks:
        return {
            "detected": True,
            "name": None,
            "evidence": f"request uji ditolak dengan status {attack.status}, request biasa tidak",
            "blocks_attacks": True,
        }
    return {"detected": False, "name": None, "evidence": None, "blocks_attacks": False}
